def build_section(rows):
    """Build a list of flowables for one section's term table."""
    data = []
    for r in rows:
        if r[0] == 'h':
            if data:
                yield _term_table(data)
                data = []
            yield sub_header(r[1], r[2])
        else:
            en, zh, note = r[1], r[2], r[3]
            data.append([
                P(en, font='Helvetica-Bold', size=8.6, color=NAVY),
                P(zh, size=8.8),
                P(note, size=8.2, color=colors.HexColor('#555555')),
            ])
    if data:
        yield _term_table(data)

def _term_table(data):
    t = Table(data, colWidths=COLW, repeatRows=0)
    style = [
        ('GRID', (0, 0), (-1, -1), 0.4, LINE),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('LEFTPADDING', (0, 0), (-1, -1), 8),
        ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ('TOPPADDING', (0, 0), (-1, -1), 3),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
    ]
    for i in range(len(data)):
        if i % 2 == 1:
            style.append(('BACKGROUND', (0, i), (-1, i), ZEBRA))
    t.setStyle(TableStyle(style))
    return t

